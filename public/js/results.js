export function determineResult(metrics) {
  const m = metrics || { load: 0, switches: 0, friction: 0, interest: 5, manual: 0, search: 0 };
  const goodMainRoute = (m.load ?? 0) <= 2
    && (m.switches ?? 0) <= 1
    && (m.friction ?? 0) <= 2
    && (m.interest ?? 5) >= 4
    && (m.manual ?? 0) <= 1
    && (m.search ?? 0) <= 1;
  if (goodMainRoute) return RESULTS.good;
  const scores = {
    load: (m.load ?? 0) * 2,
    switches: (m.switches ?? 0) * 2.3,
    manual: (m.manual ?? 0),
    search: (m.search ?? 0) * 1.2,
  };
  const dominant = Object.entries(scores).sort((a, b) => b[1] - a[1])[0][0];
  return RESULTS[dominant] || RESULTS.load;
}

export function getResultConfig(key) {
  return RESULTS[key] || RESULTS.load;
}
